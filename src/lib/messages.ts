const dictionaries: Record<LanguageCode, Record<MessageKey, string>> = {
  en,
  es,
  zh,
  vi,
  so,
  ko,
  am,
  tl,
}

export function translate(
  lang: LanguageCode,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const table = dictionaries[lang] ?? en
  return interpolate(table[key] ?? en[key] ?? String(key), vars)
}

export function translateCategory(lang: LanguageCode, category: string): string {
  const key = `category.${category}` as MessageKey
  if (Object.prototype.hasOwnProperty.call(en, key)) {
    return translate(lang, key)
  }
  return category
}

export type ActionPlanInput = {
  freeOnly?: boolean
  transportation?: string
  childrenOrFamily?: boolean
  asSoonAsPossible?: boolean
  noAppointment?: boolean
  text?: string
}

export function actionPlanSteps(lang: LanguageCode, input: ActionPlanInput): string[] {
  const steps = [
    translate(lang, 'home.next1'),
    translate(lang, 'home.next2'),
    translate(lang, 'home.next3'),
  ]
  if (input.freeOnly) steps.push(translate(lang, 'home.planFree'))
  const transportation = input.transportation?.trim().toLowerCase() ?? ''
  if (transportation.includes('wheelchair')) steps.push(translate(lang, 'home.planWheelchair'))
  else if (transportation) steps.push(translate(lang, 'home.planTransit'))
  if (input.childrenOrFamily) steps.push(translate(lang, 'home.planFamily'))
  if (input.asSoonAsPossible) steps.push(translate(lang, 'home.planAsap'))
  if (input.noAppointment) steps.push(translate(lang, 'home.planAppointment'))
  if (input.text?.trim()) steps.push(translate(lang, 'home.planDetails'))
  return steps
}
